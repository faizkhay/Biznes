// Draws each listing's wordmark as vector outlines, so a brand's lettering ships as artwork and the
// site loads no extra typeface for it. Reads the open-licence faces installed from @fontsource
// (devDependencies), sets each name at 100 units, trims to the ink, and writes
// src/data/wordmarks.ts. Run it again after changing a name, a face or the tracking:
//
//   npm run wordmarks
//
// Every face here is under the SIL Open Font License 1.1 (checked on the LICENSE file each package
// ships, and printed below when the script runs). The OFL allows outlines in a logo.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import opentype from "opentype.js";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");

/** slug, the lettering as drawn, the @fontsource package, its file, and tracking in em. */
const MARKS = [
  { slug: "lepalatier", text: "LePalatier", pkg: "cormorant-garamond", file: "cormorant-garamond-latin-500-normal.woff", face: "Cormorant Garamond Medium", tracking: 0.01 },
  { slug: "lakrem", text: "lakrem", pkg: "fredoka", file: "fredoka-latin-600-normal.woff", face: "Fredoka SemiBold", tracking: 0 },
  { slug: "souffle", text: "SOUFFLE", pkg: "jost", file: "jost-latin-300-normal.woff", face: "Jost Light", tracking: 0.32 },
  { slug: "bouke", text: "Bouké", pkg: "playfair-display", file: "playfair-display-latin-500-italic.woff", face: "Playfair Display Medium Italic", tracking: 0 },
  { slug: "larout", text: "LAROUT", pkg: "barlow-condensed", file: "barlow-condensed-latin-700-normal.woff", face: "Barlow Condensed Bold", tracking: 0.05 },
  { slug: "kazprop", text: "kazprop", pkg: "outfit", file: "outfit-latin-600-normal.woff", face: "Outfit SemiBold", tracking: -0.01 },
];

const SIZE = 100;
const round = (n) => Math.round(n * 100) / 100;

const out = {};
for (const m of MARKS) {
  const dir = dirname(require.resolve(`@fontsource/${m.pkg}/package.json`));
  const licence = readFileSync(join(dir, "LICENSE"), "utf8");
  if (!/SIL Open Font License|OFL/i.test(licence)) throw new Error(`${m.pkg}: not under the OFL, check before using`);
  const buf = readFileSync(join(dir, "files", m.file));
  const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

  // Set glyph by glyph, so tracking is exact and the last letter carries none.
  const glyphs = font.stringToGlyphs(m.text);
  const scale = SIZE / font.unitsPerEm;
  const path = new opentype.Path();
  let x = 0;
  glyphs.forEach((g, i) => {
    path.extend(g.getPath(x, 0, SIZE));
    let advance = (g.advanceWidth ?? 0) * scale;
    if (i < glyphs.length - 1) advance += font.getKerningValue(g, glyphs[i + 1]) * scale + m.tracking * SIZE;
    x += advance;
  });

  // Trim to the ink and move the outline to the origin.
  const box = path.getBoundingBox();
  for (const c of path.commands) {
    for (const k of ["x", "x1", "x2"]) if (k in c) c[k] = round(c[k] - box.x1);
    for (const k of ["y", "y1", "y2"]) if (k in c) c[k] = round(c[k] - box.y1);
  }
  out[m.slug] = { d: path.toPathData(2), w: round(box.x2 - box.x1), h: round(box.y2 - box.y1), face: m.face };
  console.log(`${m.slug.padEnd(11)} ${m.face.padEnd(32)} ${out[m.slug].w} x ${out[m.slug].h}  OFL 1.1`);
}

const file = `// Generated by scripts/make-wordmarks.mjs. Do not edit by hand: change the script and run
// \`npm run wordmarks\`. Each wordmark is the outline of its name in an open-licence face (SIL OFL
// 1.1), trimmed to the ink, on a canvas \`w\` by \`h\` units.
export type Wordmark = { d: string; w: number; h: number; face: string };

export const WORDMARKS: Record<string, Wordmark> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(join(root, "src/data/wordmarks.ts"), file);
console.log("Wrote src/data/wordmarks.ts");
