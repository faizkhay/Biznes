// The street's stills: a capture of this site's own 3D at every stop of the walk, framed for a desk
// and for a phone. They are what a visitor sees before the canvas has drawn, and instead of it
// without WebGL or without script (components/Walk.tsx), so each is the real scene, never a drawing
// of it. Also writes the link preview card (public/og.png) from the first stop.
//
//   npm run build && npx next start -p 3100 &
//   node scripts/stills.mjs [origin]            (default http://localhost:3100)
//
// It loads the home page with ?debug, which hands the scene's clock to this script
// (window.__step) and turns the camera's smoothing off, so a still is a function of the scroll
// position alone and two runs give the same picture. WebGL runs in software, so it works on a
// machine with no GPU, slowly. Each WebP gets a .json sidecar saying what it is and what made it.
//
// Needs: playwright, sharp (devDependencies).
import { chromium } from "playwright";
import { mkdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";
import { GL_ARGS, browserPath } from "./pages.mjs";

/** What every capture says about where it came from. */
const ORIGIN = "Origin: not generated by a model. A capture of this site's own 3D street (src/components/three/Street.tsx), made by scripts/stills.mjs. The sky behind the street is a generated painting whose prompt is in public/img/sky-2400.webp.json.";

const origin = process.argv[2] ?? "http://localhost:3100";
// ONLY=street,all narrows the stops, for tuning one frame without waiting for the rest.
const only = process.env.ONLY?.split(",");
const out = "public/img/walk";
mkdirSync(out, { recursive: true });

const FRAMES = [
  ["desk", { width: 1600, height: 992 }, 1],
  ["phone", { width: 390, height: 844 }, 2],
];

const browser = await chromium.launch({ executablePath: browserPath(), args: GL_ARGS });
for (const [frame, viewport, scale] of FRAMES) {
  const page = await browser.newPage({ viewport, deviceScaleFactor: scale });
  page.on("pageerror", (e) => console.log("PAGE ERROR", e.message));
  await page.goto(`${origin}/?debug`, { waitUntil: "networkidle", timeout: 180000 });
  // Wait for the canvas and its textures, then step until the scene reports a finished frame.
  await page.waitForFunction(() => typeof window.__step === "function", null, { timeout: 120000 });
  for (let i = 0; i < 60; i++) {
    const ready = await page.evaluate(() => {
      window.__step(0.1);
      return window.__street?.ready === true;
    });
    if (ready) break;
    await page.waitForTimeout(500);
  }
  const stops = await page.evaluate(() => [...document.querySelectorAll(".walk-chapter")].map((el) => el.id.replace("walk-", "")));
  // Only the street: the words, the header and the stop marks are not part of a still.
  await page.addStyleTag({ content: ".walk-chapters, .walk-stops, header { visibility: hidden !important; }" });
  for (let i = 0; i < stops.length; i++) {
    if (only && !only.includes(stops[i])) continue;
    await page.evaluate((i) => {
      const walk = document.querySelector(".walk");
      const stage = document.querySelector(".walk-stage");
      window.scrollTo(0, walk.offsetTop + i * stage.offsetHeight);
    }, i);
    await page.waitForTimeout(250);
    // A little over a second of stepped time: the camera is exact at once, and a shutter has come
    // to rest (24 frames at its rate of closing). Every stepped frame is drawn in full, and on a
    // CPU renderer a frame of this street takes up to a second, so no more are stepped than a still
    // needs, and the screenshot is given time to wait for them.
    await page.evaluate(() => window.__step(1.2));
    await page.waitForTimeout(150);
    const box = await page.locator(".walk-stage").boundingBox();
    const png = await page.screenshot({ clip: box, timeout: 180000 });
    const file = `${out}/${stops[i]}-${frame}.webp`;
    const info = await sharp(png).webp({ quality: 82 }).toFile(file);
    writeFileSync(
      `${file}.json`,
      JSON.stringify(
        {
          file: file.replace("public", ""),
          is: `The street at the "${stops[i]}" stop of the walk, framed for a ${frame === "desk" ? "wide screen" : "phone"}. A capture of this site's own 3D scene, which is built in code; the sky behind it is a generated painting (see /img/sky-2400.webp.json).`,
          made: "scripts/stills.mjs, from src/components/three/Street.tsx, through ?debug and window.__step",
          size: `${info.width} x ${info.height}`,
          // The field impeccable's provenance scan reads. No model made this picture, so it states its origin.
          prompt: ORIGIN,
        },
        null,
        2,
      ) + "\n",
    );
    console.log(`${file}  ${info.width} x ${info.height}  ${Math.round(info.size / 1024)} KB`);
    if (frame === "desk" && i === 0) {
      // The link preview card: the first screen as a visitor sees it, words and all, at 1200 x 630.
      await page.addStyleTag({ content: ".walk-chapters { visibility: visible !important; }" });
      await page.setViewportSize({ width: 1200, height: 702 });
      await page.evaluate(() => window.scrollTo(0, 0));
      await page.waitForTimeout(300);
      await page.evaluate(() => window.__step(0.2));
      await page.screenshot({ path: "public/og.png", clip: { x: 0, y: 72, width: 1200, height: 630 }, timeout: 180000 });
      writeFileSync(
        "public/og.png.json",
        JSON.stringify({ file: "/og.png", is: "The link preview card: the home page's first screen, captured from this site at 1200 x 630.", made: "scripts/stills.mjs", prompt: ORIGIN }, null, 2) + "\n",
      );
      console.log("public/og.png  1200 x 630");
      await page.setViewportSize(viewport);
      await page.addStyleTag({ content: ".walk-chapters { visibility: hidden !important; }" });
    }
  }
  await page.close();
}
await browser.close();
